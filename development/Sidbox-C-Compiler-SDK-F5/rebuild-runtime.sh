#!/usr/bin/env bash
set -euo pipefail

project=$(cd -- "$(dirname -- "$0")" && pwd)
sdk=$(cd -- "${1:?Pass the SidboxIDE or idelibs directory}" && pwd)
if [[ -f "$sdk/idelibs/api/apis.h" ]]; then
    sdk="$sdk/idelibs"
fi

arm_gcc="$sdk/tools/bin/arm-none-eabi-gcc"
arm_lld="${SIDBOX_LLD:-$sdk/tools/bin/ld.lld}"
if [[ ! -x "$arm_gcc" || ! -x "$arm_lld" || ! -f "$sdk/api/apis.h" ]]; then
    printf '%s\n' 'Select your working SidboxIDE SDK with ARM GCC and LLVM LLD.' >&2
    exit 1
fi

work=$(mktemp -d "$project/.runtime-build.XXXXXXXX")
trap 'rm -rf -- "$work"' EXIT
flags=(-mcpu=cortex-m7 -mthumb -mfpu=fpv5-d16 -mfloat-abi=hard
       -Os --specs=nano.specs -mno-unaligned-access -ffreestanding -fno-builtin
       -fPIE -fvisibility=hidden -ffunction-sections -fdata-sections
       -fno-unwind-tables -fno-asynchronous-unwind-tables
       -DSIDBOX_APPLET_V2 -I"$sdk/api" -I"$sdk/tools/cgarm/include")

"$arm_gcc" "${flags[@]}" -c "$project/runtime/program_runtime.S" -o "$work/vectors.o"
"$arm_gcc" "${flags[@]}" -c "$project/runtime/program_runtime.c" -o "$work/runtime.o"
"$arm_lld" --gc-sections --oformat=binary -T "$project/runtime/program_runtime.ld" \
    "$work/vectors.o" "$work/runtime.o" -o "$work/runtime.bin"
{
    printf '/* Generated by rebuild-runtime.sh. */\n'
    printf 'static const unsigned char sidc_runtime[] = {\n'
    od -An -v -tu1 "$work/runtime.bin" |
        awk '{printf "    "; for (i = 1; i <= NF; ++i) printf "%s, ", $i; print ""}'
    printf '};\n'
} > "$work/generated_runtime.h"
mv -- "$work/generated_runtime.h" "$project/compiler/generated_runtime.h"
printf '%s\n' 'Updated compiler/generated_runtime.h'
