def render(template, fields):
    output=[]; cursor=0
    for m in re.finditer(r'@IDE\{([A-Z_][A-Z0-9_]*)\}',template):
        key=m.group(1)
        assert key in fields,(key,template[:75])
        output.append(template[cursor:m.start()]); output.append(str(fields[key])); cursor=m.end()
    output.append(template[cursor:]); result=''.join(output)
    assert '@IDE{' not in result
    return result

def conditional(text, flags):
    out=[]; stack=[]; active=True
    for line in text.splitlines(keepends=True):
        val=line.strip()
        if val.startswith('@IDE_IF{'):
            m=re.fullmatch(r'@IDE_IF\{([A-Z_][A-Z0-9_]*)\}',val)
            assert m and m.group(1) in flags
            condition=bool(flags[m.group(1)]); stack.append((active,condition)); active=active and condition
        elif val=='@IDE_ELSE':
            parent,condition=stack[-1]; active=parent and not condition
        elif val=='@IDE_END':
            active=stack.pop()[0]
        elif active: out.append(line)
    assert not stack
    return ''.join(out)

def gcc(path,includes=()):
    subprocess.run(['gcc','-std=c11','-Wall','-Wextra','-Werror','-fsyntax-only',
                    *sum((['-I',str(i)] for i in includes),[]),str(path)],check=True,capture_output=True)

