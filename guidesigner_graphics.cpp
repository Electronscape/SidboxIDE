void drawCoderGirlCloseGlyph(
    QPainter &p,
    const QRect &rect)
{
    const int bx =
        rect.x() + 6;
    const int by =
        rect.y() + 6;
    const int bw =
        rect.width() - 12;
    const int bh =
        rect.height() - 12;

    if (bw <= 0 || bh <= 0) {
        return;
    }

    p.setPen(
        coderGirlPen(16));
    p.drawLine(
        bx,
        by,
        bx,
        by + bh - 1);
    p.drawLine(
        bx,
        by,
        bx + bw - 1,
        by);

    p.setPen(
        coderGirlPen(2));
    p.drawLine(
        bx + 1,
        by + bh - 1,
        bx + bw,
        by + bh - 1);
    p.drawLine(
        bx + bw,
        by,
        bx + bw,
        by + bh - 1);
}

