void drawCoderGirlText(
    QPainter &p,
    int x,
    int y,
    const QString &text,
    const QColor &colour)
{
    const QByteArray bytes =
        text.toLatin1();

    const int startX = x;

    for (int i = 0;
         i < bytes.size();
         ++i) {
        const unsigned char ch =
            static_cast<unsigned char>(
                bytes.at(i));

        if (ch == '\n') {
            x = startX;
            y += 16;
            continue;
        }

        const quint8 *glyph =
            kCoderGirlSystemFont[ch];

        for (int column = 0;
             column < 8;
             ++column) {
            quint8 bits =
                glyph[column];

            for (int row = 0;
                 row < 8;
                 ++row) {
                if (bits
                    & (1u << row)) {
                    p.fillRect(
                        x + column,
                        y + row * 2,
                        1,
                        2,
                        colour);
                }
            }
        }

        x += 8;
    }
}

int coderGirlTextWidth(
    const QString &text)
{
    const int newline =
        text.indexOf(
            QLatin1Char('\n'));

    const QString firstLine =
        newline >= 0
            ? text.left(newline)
            : text;

    return firstLine.toLatin1().size()
        * 8;
}

