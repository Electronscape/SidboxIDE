bool isVirtualDesignerGadget(const QString &type)
{
    return type == QStringLiteral("Messenger") || type == QStringLiteral("UART1") || type == QStringLiteral("KBInput") || type == QStringLiteral("MSInput")
        || type == QStringLiteral("Timer") || type == QStringLiteral("Media")
        || type == QStringLiteral("FileRequester") || type == QStringLiteral("MessageBox");
}

QStringList designerTabTitles(const GuiDesignerGadget &g)
{
    QStringList titles;
    for (const QString &s : g.text.split(QLatin1Char('|'))) {
        if (!s.trimmed().isEmpty()) titles << s.trimmed();
    }
    if (titles.isEmpty()) titles << QStringLiteral("Page 1");
    return titles.mid(0, 8);
}
