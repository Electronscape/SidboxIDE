bool generateGameAdventure(const QJsonObject &payload, const QString &projectRoot,
                           const QVector<GameAdventureAsset> &sprites,
                           const QVector<GameAdventureAsset> &atlases,
                           const QVector<GameAdventureAsset> &worldObjects, QString *error)
{
    const QJsonArray itemList=payload.value("items").toArray();
    const QJsonArray nodes=payload.value("nodes").toArray();
    const QJsonArray npcList=payload.value("npcs").toArray();
    if(itemList.size()>64 || nodes.size()>256 || npcList.size()>256) {
        if(error)*error=QStringLiteral("Adventure limits: 64 items, 256 dialogue nodes, 256 NPCs.");
        return false;
    }
    auto source=QString(); QTextStream c(&source);
    c << "/* GENERATED by GamerGirl. Do not edit. */\n"
         "#include \"gameadventure.h\"\n"
         "#include \"gameadventureruntime.h\"\n"
         "#include \"../gameassets/gameassets.h\"\n\n";
    if (!worldObjects.isEmpty()) c << "#include \"gameworlditems.h\"\n";
    c << "static const game_adventure_item_t items[] = {\n";
    if (itemList.isEmpty()) c << "    {0,0,0,0,0},\n";
    for (const QJsonValue &v:itemList) {
        const QJsonObject o=v.toObject();
        c << "    {" << quoted(o.value("name").toString().left(36)) << ","
          << clampInt(o,"pickupKind",0,4,0) << "u," << clampInt(o,"icon",0,255,0) << "u,"
          << clampInt(o,"capacity",1,65535,1) << "u," << clampInt(o,"initial",0,65535,0) << "u},\n";
    }
    c << "};\nstatic const game_adventure_node_t nodes[] = {\n";
    if(nodes.isEmpty())c << "    {0,0,{{0,0,-1,-1,-1,-1,-1}}},\n";
    QVector<QString> linkedActions;
    int nodeIndex = 0;
    for(const QJsonValue &v:nodes) {
        const QJsonObject o=v.toObject(); const QJsonArray choices=o.value("choices").toArray();
        c << "    {" << quoted(o.value("speaker").toString().left(36)) << ","
          << quoted(o.value("text").toString().left(512)) << ", {\n";
        for(int i=0;i<3;++i){
            const QJsonObject choice=i<choices.size()?choices[i].toObject():QJsonObject();
            int action = clampInt(choice,"action",-1,29999,-1);
            const QString targetId = choice.value("targetObjectId").toString();
            if (!targetId.isEmpty()) {
                const auto target = std::find_if(worldObjects.begin(),worldObjects.end(),
                    [&](const auto &item) { return item.id == targetId; });
                if (target == worldObjects.end()) {
                    if (error) *error = QStringLiteral("Dialogue choice refers to a deleted Game Object. Edit node %1.").arg(nodeIndex);
                    return false;
                }
                action = 30000 + nodeIndex * 3 + i;
                QString mode = choice.value("targetAction").toString("enable");
                const int modeNumber = mode == QStringLiteral("disable") ? 0 :
                                       mode == QStringLiteral("toggle") ? 2 : 1;
                linkedActions.append(QStringLiteral("    case %1: gameworlditems_set_active(%2u, %3u); break;\n")
                                     .arg(action).arg(target->worldSlot).arg(modeNumber));
            }
            c << "        {" << quoted(choice.value("text").toString().left(75)) << ","
              << quoted(choice.value("reply").toString().left(75)) << ","
              << clampInt(choice,"next",-1,nodes.size()-1,-1) << ","
              << clampInt(choice,"requires",-1,itemList.size()-1,-1) << ","
              << clampInt(choice,"give",-1,itemList.size()-1,-1) << ","
              << clampInt(choice,"take",-1,itemList.size()-1,-1) << ","
              << action << "},\n";
        }
        c << "    }},\n";
        ++nodeIndex;
    }
    c << "};\nstatic const game_adventure_npc_t npcs[] = {\n";
    int validNpcCount=0;
    QStringList animations;
    for (const QJsonValue &v:npcList) {
        const QJsonObject npc=v.toObject();
        const QString id=npc.value("spriteId").toString();
        auto it=std::find_if(sprites.begin(),sprites.end(),[&](const auto&s){return s.id==id;});
        if(it==sprites.end()) {
            if(error)*error=QStringLiteral("Adventure NPC references a missing Sprite. Reopen Adventure Editor.");
            return false;
        }
        if(nodes.isEmpty()) {
            if(error)*error=QStringLiteral("NPC '%1' needs at least one dialogue node.").arg(it->name);
            return false;
        }
        c << "    {" << it->x << "," << it->y << ","
          << std::clamp(it->width,1,1024) << "u," << std::clamp(it->height,1,1024) << "u,"
          << clampInt(npc,"radius",8,512,48) << "u,"
          << clampInt(npc,"node",0,nodes.size()-1,0) << "u},\n";
        /* Animation pointer binds to the same exported BOB used by main.c. */
        if (it->symbol.isEmpty()) {
            if (error) *error = QStringLiteral("NPC '%1' has no exported sprite symbol.").arg(it->name);
            return false;
        }
        const QJsonObject animation = npc.value("animation").toObject();
        const int cells = std::clamp(it->atlasFrames,1,256);
        auto first = [&](const char *key){return clampInt(animation,key,0,cells-1,0);};
        auto count = [&](const char *key,int base){return clampInt(animation,key,0,cells-base,0);};
        const int idleFirst = first("idleFirst"), talkFirst = first("talkFirst");
        animations.append(QStringLiteral("    {&%1,%2u,%3u,%4u,%5u,%6u,%7u},\n")
            .arg(it->symbol)
            .arg(idleFirst).arg(count("idleCount",idleFirst))
            .arg(clampInt(animation,"idleSpeed",1,60,6))
            .arg(talkFirst).arg(count("talkCount",talkFirst))
            .arg(clampInt(animation,"talkSpeed",1,60,5)));
        ++validNpcCount;
    }
    if (!validNpcCount) c << "    {0,0,0,0,0,0},\n";
    c << "};\n";
    c << "static const game_adventure_npc_animation_t npc_animations[] = {\n";
    if (animations.isEmpty()) c << "    {0,0,0,0,0,0,0},\n";
    else for (const QString &animation : animations) c << animation;
    c << "};\n";
    QJsonArray indices=payload.value("skinIndices").toArray();
    c << "static const uint16_t skin_cells[9] = {";
    for(int i=0;i<9;++i) c << (i?",":"") << std::clamp(i<indices.size()?indices[i].toInt(i):i,0,65535);
    c << "};\n";
    const QString skinId=payload.value("skinAtlasId").toString();
    auto atlas=std::find_if(atlases.begin(),atlases.end(),[&](const auto&s){return s.id==skinId;});
    QString rel;
    if (!skinId.isEmpty()) {
        if(atlas==atlases.end() || !QFileInfo::exists(atlas->path)) {
            if(error)*error=QStringLiteral("Dialogue Tile Atlas no longer exists. Choose it again.");
            return false;
        }
        rel=QDir(projectRoot).relativeFilePath(atlas->path);
        if(rel.startsWith("../") || QDir::isAbsolutePath(rel))rel=QFileInfo(atlas->path).fileName();
    }
    c << R"CG(
/* Override in a user-owned C file to perform game-specific actions, such as
   opening a locked door. Event numbers are defined in Adventure Editor. */
__attribute__((weak)) void gameadventure_on_event(uint16_t event_id)
{
    (void)event_id;
}
static void on_event(uint16_t event_id, void *user)
{
    (void)user;
    switch(event_id) {
)CG";
    for (const QString &line:linkedActions) c << line;
    c << R"CG(    default: gameadventure_on_event(event_id); break;
    }
}
void gameadventure_setup(void)
{
    const uint8_t *skin = 0;
    uint16_t width = 0, height = 0;
)CG";
    if(!rel.isEmpty()) c << "    skin = gameassets_find_ppb(" << quoted(rel) << ", &width, &height);\n";
    c << "    game_adventure_start(items," << itemList.size() << "u,nodes," << nodes.size()
      << "u,npcs," << validNpcCount << "u,skin,width,height,"
      << clampInt(payload,"tileSize",4,32,8) << "u,skin_cells,"
      << clampInt(payload,"framesPerChar",1,30,2) << "u,on_event,0);\n"
      << "    game_adventure_text_style("
      << clampInt(payload,"textColourIndex",0,255,15) << "u,"
      << (payload.value("textOutline").toBool(false) ? "1u" : "0u") << ","
      << clampInt(payload,"outlineColourIndex",0,255,1) << "u);\n"
      << "    game_adventure_npc_animations(npc_animations," << validNpcCount << "u);\n}\n";
    const QString header=QStringLiteral(
        "/* GENERATED by GamerGirl. Do not edit. */\n"
        "#ifndef GAMERGIRL_GENERATED_ADVENTURE_H\n"
        "#define GAMERGIRL_GENERATED_ADVENTURE_H\n"
        "#include <stdint.h>\n"
        "#include \"gameadventureruntime.h\"\n"
        "void gameadventure_setup(void);\n"
        "void gameadventure_on_event(uint16_t event_id);\n"
        "#endif\n");
    const QDir out(QDir(projectRoot).filePath("gamehelpers"));
    if(!QDir().mkpath(out.absolutePath())) {
        if(error)*error=QStringLiteral("Cannot create gamehelpers directory"); return false;
    }
    if(!save(out.filePath("gameadventure.h"),header,error))return false;
    return save(out.filePath("gameadventure.c"),source,error);
}
